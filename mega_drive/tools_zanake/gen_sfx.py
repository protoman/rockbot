#!/usr/bin/env python3
"""Copy the sound effects named in a manifest out of a GameMaker project.

Usage: gen_sfx.py MANIFEST.json GM_SOUNDS_DIR RES_DIR

Reads the list "sounds" and writes to RES_DIR:
  sfx/NAME.wav   the original's sounds/xNAME/xNAME, which is a WAV file,
                 made louder
  sfx.res        a rescomp resource file, which converts each to what the
                 XGM2 driver plays: 8 bit at 13.3 kHz
"""

import array
import json
import os
import sys
import wave

# Most of the originals peak well under half of full scale, which is quiet
# next to other games on the console. All get the same gain, so they keep
# their balance; the few loud ones are clipped.
GAIN = 2


def copy_louder(source, target):
    with wave.open(source, 'rb') as wav:
        params = wav.getparams()
        data = wav.readframes(params.nframes)
    if params.sampwidth == 1:
        samples = [(byte - 128) << 8 for byte in data]
    elif params.sampwidth == 2:
        samples = array.array('h', data)
        if sys.byteorder == 'big':
            samples.byteswap()
    else:
        sys.exit('%s: %d bit sound not supported' % (source, params.sampwidth * 8))
    louder = array.array('h', (max(-32768, min(32767, sample * GAIN)) for sample in samples))
    if sys.byteorder == 'big':
        louder.byteswap()
    with wave.open(target, 'wb') as wav:
        wav.setnchannels(params.nchannels)
        wav.setsampwidth(2)
        wav.setframerate(params.framerate)
        wav.writeframes(louder.tobytes())


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    manifest_path, sounds_dir, res_dir = sys.argv[1:]
    names = json.load(open(manifest_path, encoding='utf-8'))['sounds']
    sfx_dir = os.path.join(res_dir, 'sfx')
    os.makedirs(sfx_dir, exist_ok=True)

    lines = ['// Generated by tools/gen_sfx.py from res/sfx.json. Do not edit.', '']
    for name in names:
        source = os.path.join(sounds_dir, 'x' + name, 'x' + name)
        if not os.path.isfile(source):
            sys.exit('sound %s not found in %s' % (name, sounds_dir))
        copy_louder(source, os.path.join(sfx_dir, name + '.wav'))
        lines.append('WAV sfx_%s "sfx/%s.wav" XGM2' % (name, name))
    with open(os.path.join(res_dir, 'sfx.res'), 'w', encoding='utf-8') as out:
        out.write('\n'.join(lines) + '\n')
    print('%d sounds' % len(names))


if __name__ == '__main__':
    main()
