#!/usr/bin/env python3
"""Extract the rooms of fixed layout from the GameMaker source.

The title, the tutorial, the high scores and the bonus rooms are rooms the
player walks about in, built of a level's blocks. This reads their room
files and writes src/rooms_fixed.h: each room as rows of characters, one per
block, and a list of the things that stand in it, by the name of the
original's object and its place in pixels. Run with "python3 -I".

usage: gen_fixed_rooms.py ROOMS_DIR OUT.h
"""

import json
import os
import re
import sys

# Room, its name here, and how many columns of it to keep: the title's last
# eight are solid filler.
ROOMS = [('rTitle', 'title', 40), ('rTutorial', 'tutorial', None), ('rHighscores', 'scores', None),
         ('rSun', 'sun', None), ('rMoon', 'moon', None), ('rStars', 'stars', None)]

# Objects that are one block of the level, and the character for each.
BLOCKS = {
    'oBrick': 'b', 'oHardBlock': 'h', 'oBrickSmooth': 's', 'oDark': 'd', 'oRope': 'r',
    'oLadderOrange': 'L', 'oLadderTop': 'P', 'oVine': 'v', 'oSpikes': '^',
    'oEntrance': 'e', 'oExit': 'x', 'oLava': 'w', 'oLavaSolid': 'W', 'oBlack': '#',
    # Doors that lead somewhere else than the next level.
    'oXStart': 'S', 'oXScores': 'C', 'oXTutorial': 'U', 'oXTitle': 'T', 'oXShortcut5': '5',
    'oSpearTrapTop': 'i', 'oSpearTrapBottom': 'j', 'oArrowRepeaterL': '<', 'oArrowRepeaterR': '>',
}

# Objects that only run the room, or frame its text; nothing to place.
IGNORED = {'oGame', 'oBricks', 'oLevel', 'oMenu', 'oTitle', 'oHighscores', 'oSunRoom', 'oMoonRoom',
           'oStarsRoom', 'oTitleLogo_HD', 'oTitleBG_HD', 'oGlobals'}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    rooms = []
    kinds = []
    for room_name, name, keep in ROOMS:
        path = os.path.join(sys.argv[1], room_name, room_name + '.yy')
        room = json.loads(re.sub(r',(\s*[}\]])', r'\1', open(path, encoding='utf-8').read()))
        width = keep or room['roomSettings']['Width'] // 16
        height = room['roomSettings']['Height'] // 16
        rows = [['.'] * width for _ in range(height)]
        things = []

        def walk(node):
            if isinstance(node, dict):
                if node.get('objectId') and 'x' in node:
                    kind = node['objectId']['name']
                    x, y = int(node['x']), int(node['y'])
                    inside = 0 <= x < width * 16 and 0 <= y < height * 16
                    if kind in BLOCKS:
                        if inside:
                            rows[y // 16][x // 16] = BLOCKS[kind]
                    elif kind not in IGNORED and not kind.startswith('oMenu') and inside:
                        things.append((kind, x, y))
                        if kind not in kinds:
                            kinds.append(kind)
                for value in node.values():
                    walk(value)
            elif isinstance(node, list):
                for value in node:
                    walk(value)

        walk(room)
        rooms.append((name, width, height, rows, sorted(things, key=lambda t: (t[2], t[1], t[0]))))

    def thing_id(kind):
        return 'THING_' + re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', kind[1:]).upper()

    out = ['// Generated by tools/gen_fixed_rooms.py from the room files. Do not edit.',
           '//',
           '// b brick, h brick that nothing breaks, s smooth brick, d dark rock, r rope,',
           '// L ladder, P ladder top, v vine, ^ spikes, e the way in, x the way out, w lava,',
           '// W the solid under lava, # the black behind text, i j a spear trap, < > arrow',
           '// traps that never run out. Doors: S start, C scores, U tutorial, T title, 5 the',
           '// first shortcut.',
           '#ifndef ROOMS_FIXED_H', '#define ROOMS_FIXED_H', '',
           '// What stands in a room, by the original\'s object.',
           'enum {']
    out += ['    %s,' % thing_id(kind) for kind in kinds]
    out += ['    THING_COUNT', '};', '',
            'typedef struct {', '    u8 kind;', '    s16 x, y; // in pixels, as the room file has it',
            '} RoomThing;', '']
    for name, width, height, rows, things in rooms:
        upper = name.upper()
        out += ['#define %s_ROOM_WIDTH %d' % (upper, width), '#define %s_ROOM_HEIGHT %d' % (upper, height),
                'static const char %s_room[%s_ROOM_HEIGHT][%s_ROOM_WIDTH + 1] = {' % (name, upper, upper)]
        out += ['    "%s",' % ''.join(row) for row in rows]
        out += ['};', 'static const RoomThing %s_room_things[] = {' % name]
        out += ['    { %s, %d, %d },' % (thing_id(kind), x, y) for kind, x, y in things]
        out += ['};', '']
    out += ['#endif', '']
    open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(out))


if __name__ == '__main__':
    main()
