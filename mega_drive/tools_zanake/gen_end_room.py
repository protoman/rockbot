#!/usr/bin/env python3
"""Extract the ending's treasure room from the GameMaker source.

Reads rooms/rEnd/rEnd.yy and writes src/room_end.h: the room as rows of
characters, one per block, and where its other things stand. Run with
"python3 -I".

usage: gen_end_room.py REND.yy OUT.h
"""

import json
import re
import sys

BLOCKS = {'oBrick': 'b', 'oTemple': 't', 'oLava': 'w', 'oLavaSolid': 's', 'oEntrance': 'e'}
PLACES = {'oPDummy': 'PLAYER', 'oBigChest': 'CHEST', 'oEndPlat': 'PLATFORM', 'oEndWall': 'WALL'}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    text = open(sys.argv[1], encoding='utf-8').read()
    room = json.loads(re.sub(r',(\s*[}\]])', r'\1', text))
    width = room['roomSettings']['Width'] // 16
    height = room['roomSettings']['Height'] // 16
    rows = [['.'] * width for _ in range(height)]
    places = {}

    def walk(node):
        if isinstance(node, dict):
            if node.get('objectId') and 'x' in node:
                name = node['objectId']['name']
                x, y = int(node['x']), int(node['y'])
                if name in BLOCKS and 0 <= x // 16 < width and 0 <= y // 16 < height:
                    rows[y // 16][x // 16] = BLOCKS[name]
                elif name in PLACES:
                    places[PLACES[name]] = (x, y)
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    walk(room)
    out = ['// Generated by tools/gen_end_room.py from rEnd.yy. Do not edit.',
           '//',
           '// b brick, t temple brick, w lava, s the solid under the lava, e the door.',
           '#ifndef ROOM_END_H', '#define ROOM_END_H', '',
           '#define END_ROOM_WIDTH %d' % width, '#define END_ROOM_HEIGHT %d' % height, '']
    for name in sorted(places):
        out.append('#define END_%s_X %d' % (name, places[name][0]))
        out.append('#define END_%s_Y %d' % (name, places[name][1]))
    out += ['', 'static const char end_room[END_ROOM_HEIGHT][END_ROOM_WIDTH + 1] = {']
    out += ['    "%s",' % ''.join(row) for row in rows]
    out += ['};', '', '#endif', '']
    open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(out))


if __name__ == '__main__':
    main()
