#!/usr/bin/env python3
"""Extract the temple's and Olmec's room templates from the GameMaker source.

Reads scripts/scrRoomGen4/scrRoomGen4.gml and scripts/scrRoomGen5/scrRoomGen5.gml
and writes src/rooms_temple.h. The templates are copied character for
character, in the order of the scripts; only their grouping into C arrays is
decided here. The shops are left out: they are the mines' with other walls.
Run with "python3 -I".

usage: gen_rooms_temple.py SCR_ROOM_GEN4.gml SCR_ROOM_GEN5.gml OUT.h
"""

import re
import sys

# Arrays in source order, with how many templates each takes. None is skipped.
TEMPLE_ROOMS = [
    ('temple_rooms_start', 2),
    ('temple_rooms_end', 1),
    # Nine rooms, the sun room twice over, one more, the idol's, three
    # treasure vaults and Kali's altar.
    ('temple_rooms_side', 17),
    # The last two hold the Tomb Lord, in the City of Gold.
    ('temple_rooms_main', 12),
    ('temple_rooms_drop_in', 4),
    (None, 6),
    ('temple_rooms_xoc', 1),
    ('temple_rooms_pit_top', 1),
    ('temple_rooms_pit', 1),
    ('temple_rooms_pit_bottom', 1),
    ('temple_rooms_drop', 8),
]
TEMPLE_OBSTACLES = [('temple_obstacles_door', 1), ('temple_obstacles_ground', 8), ('temple_obstacles_air', 10)]

OLMEC_ROOMS = [('olmec_rooms_top', 6), ('olmec_rooms_bottom', 6)]
OLMEC_OBSTACLES = [(None, 1), (None, 8), ('olmec_obstacles_air', 6)]


def templates(path):
    text = open(path, encoding='utf-8').read()
    # The first assignment is an all-empty default, before any branch.
    rooms = re.findall(r'strTemp = "([^"]{80})"', text)[1:]
    wide = re.findall(r'strObs1 = "(\w{5})"; strObs2 = "(\w{5})"; strObs3 = "(\w{5})";', text)
    narrow = re.findall(r'strObs1 = "(\w{4})"; strObs2 = "(\w{4})"; strObs3 = "(\w{4})";', text)
    return rooms, wide, narrow


def emit(out, groups, items, cells):
    at = 0
    for name, count in groups:
        chosen = items[at:at + count]
        at += count
        if name is None:
            continue
        if len(chosen) != count:
            sys.exit('%s: expected %d, found %d' % (name, count, len(chosen)))
        out.append('static const char %s[%d][%d] = {' % (name, count, cells + 1))
        out += ['    "%s",' % (item if isinstance(item, str) else ''.join(item)) for item in chosen]
        out += ['};', '']
    if at != len(items):
        sys.exit('%d templates left over' % (len(items) - at))


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    out = ['// Generated by tools/gen_rooms_temple.py from scrRoomGen4.gml and scrRoomGen5.gml.',
           '// Do not edit.',
           '//',
           '// As rooms_mines.h, which goes first. The last obstacles are 4x3.',
           '#ifndef ROOMS_TEMPLE_H', '#define ROOMS_TEMPLE_H', '']
    rooms, wide, narrow = templates(sys.argv[1])
    # The three leading all-empty obstacles are the loop's defaults.
    emit(out, TEMPLE_ROOMS, rooms, 80)
    emit(out, TEMPLE_OBSTACLES, wide, 15)
    emit(out, [('temple_obstacles_narrow', 10)], narrow, 12)
    rooms, wide, _ = templates(sys.argv[2])
    emit(out, OLMEC_ROOMS, rooms, 80)
    emit(out, OLMEC_OBSTACLES, wide, 15)
    out += ['#endif', '']
    open(sys.argv[3], 'w', encoding='utf-8').write('\n'.join(out))


if __name__ == '__main__':
    main()
