#!/usr/bin/env python3
"""PC game_credits.txt -> src/credits_data.c/h for the ending scroll."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ROCKBOT = os.path.dirname(ROOT)
SRC = os.path.join(ROOT, "data/games/RockDroid1/game_credits.txt")
OUT = os.path.join(ROOT, "src")


def esc(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    lines = []
    for line in open(SRC, encoding="latin1"):
        line = line.rstrip("\r\n")
        if line.startswith("#"):
            continue
        if len(line) > 38:
            line = line[:38]
        lines.append(line)
    with open(os.path.join(OUT, "credits_data.h"), "w") as f:
        f.write("#ifndef CREDITS_DATA_H\n#define CREDITS_DATA_H\n\n"
                "#include <genesis.h>\n\n"
                "// Generated by tools/convert_credits.py.\n"
                f"#define CREDITS_LINES {len(lines)}\n"
                "extern const char *const credits_lines[CREDITS_LINES];\n\n"
                "#endif\n")
    with open(os.path.join(OUT, "credits_data.c"), "w") as f:
        f.write('#include "credits_data.h"\n\n'
                "const char *const credits_lines[CREDITS_LINES] = {\n")
        for line in lines:
            f.write("    " + esc(line) + ",\n")
        f.write("};\n")
    print(f"wrote src/credits_data.c/h ({len(lines)} lines)")


if __name__ == "__main__":
    main()
