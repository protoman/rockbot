#!/usr/bin/env python3
"""Decompose the PC save-selector bars into an SGDK tilemap for the MD.

PC scenesLib::select_save (sceneslib.cpp:755) draws 5 slots from
save_selector_enabled.png / save_selector_disabled.png at x=0, 40px tall.
Both art files have IDENTICAL pixel indices and differ only in palette, so
one tileset + two palette lines is enough (enabled = selected row).

The interior of the bar is the game colorkey (transparent) -> palette index 0
becomes the plane colour behind the row (black, like PC blank_screen).

Emits src/saveselect_data.{c,h}:
  packed 4bpp tiles + the 40x5 row tilemap + enabled/disabled palettes.
No rescomp TILESET: it reorders tiles and would break the hand-made map.

Usage: python3 tools/convert_save_selector.py
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
IMAGES = os.path.join(ROOT, "images")
SRC = os.path.join(ROOT, "src")

TILE = 8
BASE_TILE = 16            # TILE_USER_INDEX
MD_LEVELS = (0, 36, 73, 109, 146, 182, 219, 255)


def md_round(v):
    return min(MD_LEVELS, key=lambda x: abs(x - v))


def vdp(c):
    c = (md_round(c[0]), md_round(c[1]), md_round(c[2]))
    # MD CRAM word: R bits 1-3, G bits 5-7, B bits 9-11 (white = 0x0EEE).
    return ((MD_LEVELS.index(c[0]) << 1) | (MD_LEVELS.index(c[1]) << 5)
            | (MD_LEVELS.index(c[2]) << 9))


def load_p(path):
    im = Image.open(os.path.join(IMAGES, path))
    assert im.mode == "P", f"{path}: not indexed (run tools/import_pc_art.py)"
    return im, [tuple(im.getpalette()[i * 3:i * 3 + 3]) for i in range(16)]


def main():
    en, pal_en = load_p("backgrounds/save_selector_enabled.png")
    dis, pal_dis = load_p("backgrounds/save_selector_disabled.png")
    assert en.size == dis.size == (320, 40), (en.size, dis.size)
    # The two bars are the same geometry with a palette swap, but the
    # importer now derives each one's palette independently, so their pixel
    # INDICES differ. Use the enabled indices as canonical and rebuild the
    # disabled palette per enabled index from the colour at the same pixel.
    from collections import Counter
    e2d = {}
    for ep, dp in zip(en.getdata(), dis.getdata()):
        if ep == 0:
            continue
        e2d.setdefault(ep, Counter())[pal_dis[dp]] += 1
    dis_pal = [(0, 0, 0)] * 16
    for e_idx, cnt in e2d.items():
        dis_pal[e_idx] = cnt.most_common(1)[0][0]
    pal_dis = dis_pal

    w, h = en.size
    cw, ch = w // TILE, h // TILE          # 40 x 5
    src = en.load()

    tiles, index = [], {}

    def tile_of(cx, cy):
        idx = bytes(src[cx * TILE + x, cy * TILE + y]
                    for y in range(TILE) for x in range(TILE))
        n = index.get(idx)
        if n is None:
            n = index[idx] = len(tiles)
            tiles.append(idx)
        return n

    tilemap = [[tile_of(cx, cy) for cx in range(cw)] for cy in range(ch)]
    print(f"save selector: {w}x{h} -> {cw}x{ch} cells, {len(tiles)} unique tiles")

    # packed 4bpp, tile-major (all rows of tile 0, then tile 1, ...)
    packed = []
    for idx in tiles:
        for y in range(TILE):
            for xb in range(TILE // 2):
                packed.append((idx[y * TILE + xb * 2] << 4)
                              | idx[y * TILE + xb * 2 + 1])
    words = [(packed[i] << 24) | (packed[i + 1] << 16) |
             (packed[i + 2] << 8) | packed[i + 3]
             for i in range(0, len(packed), 4)]

    # index 0 is the transparent interior -> black plane colour; entry 4 is
    # the black outline and stays black.
    for pal in (pal_en, pal_dis):
        pal[0] = (0, 0, 0)

    hdr = f"""#ifndef SAVESELECT_DATA_H
#define SAVESELECT_DATA_H

#include <genesis.h>

// Generated by tools/convert_save_selector.py. Do not edit by hand.
#define SAVE_TILE_BASE {BASE_TILE}
#define SAVE_TILE_COUNT {len(tiles)}
#define SAVE_ROW_W {cw}
#define SAVE_ROW_H {ch}

// 40x{ch} row tilemap (local tile indices; add SAVE_TILE_BASE).
extern const u16 saveselect_map[SAVE_ROW_W * SAVE_ROW_H];
extern const u32 saveselect_tiles_data[SAVE_TILE_COUNT * 8];
extern const u16 saveselect_pal_en[16];
extern const u16 saveselect_pal_dis[16];

#endif
"""
    c = ['#include "saveselect_data.h"\n\n']
    c.append(f"const u32 saveselect_tiles_data[{len(tiles) * 8}] = {{\n")
    for i in range(0, len(words), 8):
        c.append("    " + ", ".join(f"0x{w:08X}" for w in words[i:i + 8]) + ",\n")
    c.append("};\n\n")
    c.append(f"const u16 saveselect_map[{cw * ch}] = {{\n")
    for row in tilemap:
        c.append("    " + ", ".join(str(v) for v in row) + ",\n")
    c.append("};\n\n")
    for name, pal in (("saveselect_pal_en", pal_en),
                      ("saveselect_pal_dis", pal_dis)):
        c.append(f"const u16 {name}[16] = {{\n    "
                 + ", ".join(f"0x{vdp(x):03X}" for x in pal) + "\n};\n\n")

    with open(os.path.join(SRC, "saveselect_data.h"), "w") as f:
        f.write(hdr)
    with open(os.path.join(SRC, "saveselect_data.c"), "w") as f:
        f.writelines(c)
    print("wrote src/saveselect_data.h/.c")
    return 0


if __name__ == "__main__":
    sys.exit(main())
