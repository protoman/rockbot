#!/usr/bin/env python3
"""PC in-game menu armor-piece icons -> MD plane tiles.

PC draw::weapon_menu_show_player (graphic/draw.cpp:1021-1040) draws, next to the
player portrait, the three installed armor pieces over a base icon:
`images/backgrounds/player_armor_pieces.png` is 4 columns x 4 rows of 28x29 —
one row per player, columns base / ARMS / BODY / LEGS.

A plane cannot stack transparent tiles, so the eight combinations are
pre-composited here and the menu picks one (mask = player.armor bits). The art
is quantised to the player's own PAL2 palette (the portrait next to it uses the
same line), padded to 4x4 8x8 tiles.

Outputs: res/menu_armor_pal.png (reference), src/menu_armor_data.{c,h}
Usage:  tools/convert_menu_armor.py [--preview out.png]
"""
import argparse
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PC_ART = os.path.join(ROOT, "data/games/RockDroid1/images/backgrounds/"
                            "player_armor_pieces.png")
RES = os.path.join(ROOT, "res")
SRC = os.path.join(ROOT, "src")

CW, CH = 28, 29            # one icon cell in the PC art
TILE = 8
COLS, ROWS = 4, 4          # 32x32 padded frame
PLAYERS = 4
MASKS = 8                  # arms / body / legs


def load_palette(player):
    """PAL2 for that player, from the port's own sprite sheet."""
    path = os.path.join(RES, f"player_p{player + 1}.png")
    im = Image.open(path)
    if im.mode != "P":
        im = im.convert("P", palette=Image.ADAPTIVE, colors=16)
    pal = im.getpalette()
    return [tuple(pal[i * 3:i * 3 + 3]) for i in range(16)]


def nearest(palette, rgb, skip0=True):
    best, bestd = 0, 1 << 30
    for i, c in enumerate(palette):
        if skip0 and i == 0:
            continue
        d = (c[0] - rgb[0]) ** 2 + (c[1] - rgb[1]) ** 2 + (c[2] - rgb[2]) ** 2
        if d < bestd:
            bestd, best = d, i
    return best


def cell(art, col, row):
    return art.crop((col * CW, row * CH, (col + 1) * CW, (row + 1) * CH))


def compose(base, pieces, mask):
    out = base.copy()
    for i, piece in enumerate(pieces):
        if mask & (1 << i):
            out.alpha_composite(piece)
    return out


def to_indices(img, palette):
    px = img.load()
    out = [[0] * (COLS * TILE) for _ in range(ROWS * TILE)]
    for y in range(ROWS * TILE):
        for x in range(COLS * TILE):
            r, g, b, a = px[x, y] if (x < CW and y < CH) else (0, 0, 0, 0)
            out[y][x] = nearest(palette, (r, g, b)) if a >= 128 else 0
    return out


def tiles_from(indices):
    """SGDK tile = 8 rows, each a u32 of 8 4bpp pixels (high nibble first)."""
    tiles = []
    for ty in range(ROWS):
        for tx in range(COLS):
            for row in range(TILE):
                v = 0
                for i in range(TILE):
                    v = (v << 4) | (indices[ty * TILE + row][tx * TILE + i] & 0xF)
                tiles.append(v)
    return tiles


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview")
    args = ap.parse_args()

    if not os.path.exists(PC_ART):
        sys.exit(f"missing PC art: {PC_ART}")
    art = Image.open(PC_ART).convert("RGBA")
    if art.size != (CW * 4, CH * 4):
        sys.exit(f"{PC_ART}: expected {CW*4}x{CH*4}, got {art.size}")

    data = []
    for p in range(PLAYERS):
        palette = load_palette(p)
        base = cell(art, 0, p)
        pieces = [cell(art, 1, p), cell(art, 2, p), cell(art, 3, p)]
        for mask in range(MASKS):
            data.append(tiles_from(to_indices(compose(base, pieces, mask),
                                              palette)))

    ntiles = ROWS * COLS
    with open(os.path.join(SRC, "menu_armor_data.c"), "w") as f:
        f.write("// Generated by tools/convert_menu_armor.py - do not edit.\n")
        f.write("// PC player_armor_pieces.png: 4 players x 8 masks, 4x4 tiles.\n")
        f.write('#include "menu_armor_data.h"\n\n')
        f.write(f"const u32 menu_armor_tiles[4][8][{ntiles * 8}] = {{\n")
        for p in range(PLAYERS):
            f.write(f"    {{  // player {p + 1}\n")
            for mask in range(MASKS):
                f.write("        {\n")
                t = data[p * MASKS + mask]
                for i in range(0, len(t), 4):
                    f.write("            " +
                            ", ".join(f"0x{v:08X}" for v in t[i:i + 4]) + ",\n")
                f.write("        },\n")
            f.write("    },\n")
        f.write("};\n")
    with open(os.path.join(SRC, "menu_armor_data.h"), "w") as f:
        f.write("#ifndef MENU_ARMOR_DATA_H\n#define MENU_ARMOR_DATA_H\n\n")
        f.write("#include <genesis.h>\n\n")
        f.write(f"#define MENU_ARMOR_TILES {ntiles}\n")
        f.write("extern const u32 menu_armor_tiles[4][8][MENU_ARMOR_TILES * 8];\n\n")
        f.write("#endif\n")

    print(f"wrote src/menu_armor_data.c/h: {PLAYERS}x{MASKS} frames of "
          f"{COLS}x{ROWS} tiles ({ntiles} tiles each)")

    if args.preview:
        # contact sheet: one row per player, masks left to right
        sheet = Image.new("RGB", (MASKS * COLS * TILE, PLAYERS * ROWS * TILE),
                          (0, 0, 0))
        for p in range(PLAYERS):
            palette = load_palette(p)
            base = cell(art, 0, p)
            pieces = [cell(art, 1, p), cell(art, 2, p), cell(art, 3, p)]
            for mask in range(MASKS):
                img = compose(base, pieces, mask)
                thumb = Image.new("RGB", (COLS * TILE, ROWS * TILE), (0, 0, 0))
                thumb.paste(img, (0, 0), img)
                sheet.paste(thumb, (mask * COLS * TILE, p * ROWS * TILE))
        sheet.save(args.preview)
        print(f"wrote {args.preview}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
