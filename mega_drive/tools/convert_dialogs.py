#!/usr/bin/env python3
"""Pack the PC stage dialog files into C.

build/games/RockDroid1/dialogs/stage_dialogs_<n>.dat (60 lines, English):
  0..5    stage-start "person" lines
  6..29   stage-start per-player lines (4 players x 6)
  30..35  boss lines (two 3-line pages)
  36..59  boss per-player lines (player p: 36 + p*6)

The PC game only ever displays the boss block (scenes/dialogs.cpp:249,
show_boss_dialog): the stage-start lines are generated by the editor but no
code path reads them. The port keeps them in the table for completeness.

Usage: python3 tools/convert_dialogs.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ROCKBOT = os.path.dirname(ROOT)
DATA = os.path.join(ROCKBOT, "build/games/RockDroid1/dialogs")
SRC = os.path.join(ROOT, "src")

STAGES = 14
LINES = 60


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    table = []
    for n in range(STAGES):
        path = os.path.join(DATA, f"stage_dialogs_{n}.dat")
        lines = []
        if os.path.exists(path):
            raw = open(path, "rb").read().decode("utf-8", "replace")
            lines = raw.splitlines()
        lines += [""] * (LINES - len(lines))
        for i, line in enumerate(lines[:LINES]):
            if any(ord(c) < 32 or ord(c) > 126 for c in line):
                sys.exit(f"stage_dialogs_{n}.dat line {i} is not ASCII: {line!r}")
        table.append(lines)

    with open(os.path.join(SRC, "dialogs_data.h"), "w") as f:
        f.write("#ifndef DIALOGS_DATA_H\n#define DIALOGS_DATA_H\n\n"
                "#include <genesis.h>\n\n"
                "// Generated by tools/convert_dialogs.py.\n"
                f"#define DIALOG_STAGES {STAGES}\n"
                f"#define DIALOG_LINES {LINES}\n\n"
                "extern const char *const stage_dialogs"
                "[DIALOG_STAGES][DIALOG_LINES];\n\n#endif\n")

    with open(os.path.join(SRC, "dialogs_data.c"), "w") as f:
        f.write('#include "dialogs_data.h"\n\n'
                "const char *const stage_dialogs"
                "[DIALOG_STAGES][DIALOG_LINES] = {\n")
        for lines in table:
            f.write("    {\n")
            for line in lines:
                f.write("        " + cstr(line) + ",\n")
            f.write("    },\n")
        f.write("};\n")
    print(f"wrote src/dialogs_data.h/.c ({STAGES} stages x {LINES} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
