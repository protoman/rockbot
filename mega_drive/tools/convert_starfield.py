#!/usr/bin/env python3
"""Credits star field (PC draw::show_credits_text: star_field1.png slow, star_field2.png
fast, both 320x240, colorkey 75,125,125 transparent) -> src/starfield_data.c/h.

The MD has one BG plane for the two layers, but vertical scroll can be set per
2-tile column. The two layers are therefore folded into alternating 16 px bands:
layer 1 (slow) in the even bands, layer 2 (fast) in the odd ones; the ROM scrolls
each band set at its own speed. A star of source band b lands in band
(b // 2) * 2 + layer, so no star is lost (two source bands share one).
The plane is 256 px tall (32 rows); the 240 px art wraps at 256.
"""
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PCIMG = os.path.join(os.path.dirname(ROOT), "build", "shared", "images")
SRC = os.path.join(ROOT, "src")
KEY = (75, 125, 125)
LEVELS = (0, 36, 73, 109, 146, 182, 219, 255)


def md(v):
    return min(LEVELS, key=lambda l: abs(l - v))


def stars(name):
    im = Image.open(os.path.join(PCIMG, name)).convert("RGBA")
    px = im.load()
    out = []
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = px[x, y]
            if a == 0 or (r, g, b) == KEY or (r, g, b) == (0, 0, 0):
                continue
            out.append((x, y, (md(r), md(g), md(b))))
    return out


def main():
    canvas = {}                                   # (x, y) -> colour
    for layer, name in ((0, "star_field1.png"), (1, "star_field2.png")):
        for x, y, c in stars(name):
            band = ((x >> 4) >> 1) * 2 + layer
            canvas[(band * 16 + (x & 15), y)] = c
    pal = sorted({c for c in canvas.values()})
    assert len(pal) <= 8, pal
    tiles, tile_idx, tmap = [bytes(32)], {bytes(32): 0}, []
    for ty in range(32):
        for tx in range(40):
            t = bytearray(32)
            for yy in range(8):
                for xx in range(8):
                    c = canvas.get((tx * 8 + xx, ty * 8 + yy))
                    if c is None:
                        continue
                    i = pal.index(c) + 1
                    o = yy * 4 + (xx >> 1)
                    t[o] |= i << (4 if xx % 2 == 0 else 0)
            t = bytes(t)
            if t not in tile_idx:
                tile_idx[t] = len(tiles)
                tiles.append(t)
            tmap.append(tile_idx[t])
    with open(os.path.join(SRC, "starfield_data.h"), "w") as f:
        f.write("#ifndef STARFIELD_DATA_H\n#define STARFIELD_DATA_H\n\n#include <genesis.h>\n\n"
                "// Generated by tools/convert_starfield.py (credits star layers, see the script).\n"
                f"#define STARFIELD_TILES {len(tiles)}\n#define STARFIELD_COLORS {len(pal)}\n"
                "extern const u32 starfield_tiles[STARFIELD_TILES * 8];\n"
                "extern const u16 starfield_map[40 * 32];      // tile index (relative to the base)\n"
                "extern const u16 starfield_pal[STARFIELD_COLORS];   // VDP colours for palette entries 1..\n\n#endif\n")
    with open(os.path.join(SRC, "starfield_data.c"), "w") as f:
        f.write('#include "starfield_data.h"\n\nconst u32 starfield_tiles[STARFIELD_TILES * 8] = {\n')
        for t in tiles:
            f.write("    " + ", ".join("0x%08X" % int.from_bytes(t[i:i + 4], "big") for i in range(0, 32, 4)) + ",\n")
        f.write("};\n\nconst u16 starfield_map[40 * 32] = {\n")
        for i in range(0, len(tmap), 20):
            f.write("    " + ", ".join(str(v) for v in tmap[i:i + 20]) + ",\n")
        f.write("};\n\nconst u16 starfield_pal[STARFIELD_COLORS] = {\n    ")
        f.write(", ".join("0x%03X" % ((c[2] // 36) << 9 | (c[1] // 36) << 5 | (c[0] // 36) << 1) for c in pal))
        f.write("\n};\n")
    print(f"wrote src/starfield_data.c/h: {len(tiles)} tiles, {len(pal)} colours, "
          f"{len(canvas)} stars")


if __name__ == "__main__":
    main()
