#!/usr/bin/env python3
"""Read the 4 PC players (player_list_v3_1_1.dat) into a generated table.

The PC record struct (format_v4::file_player_v3_1_1) is 6216 bytes and its
field offsets are easy to get wrong by hand (st_color is 3 x Sint16, alignment
padding, ...). So instead of re-deriving them, this tool compiles a tiny C++
dumper that includes the PC header, reads the file with the REAL struct and
prints the fields; Python parses that and emits the table. Host g++ only.

Emitted per player: name, all 12 `weapon_colors` (c1/c2/c3 each — the runtime
swaps palette indices 13/14/15 with the SELECTED weapon's colours), and the
ability flags/fields. Weapon 0's colours are also exposed as c1/c2/c3, which
convert_player.py bakes into the sprite sheets.

Writes src/player_data.{c,h}. Used by convert_player.py (palette-swap colours)
and by the runtime (abilities/names/weapon palettes).

Usage: python3 tools/convert_players.py
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ROCKBOT = os.path.dirname(ROOT)
SRC = os.path.join(ROOT, "src")
WORK = "/tmp/opencode"

FL_SHIELD, FL_SLIDE, FL_CHARGE, FL_DJUMP, FL_AIRDASH, FL_DIAG = (
    1, 2, 4, 8, 16, 32)

WEAPON_N = 12

DUMPER = r'''
#include "file/v4/file_game_v4.h"
#include <cstdio>
int main() {
    using namespace format_v4;
    FILE* f = fopen("build/games/RockDroid1/player_list_v3_1_1.dat", "rb");
    if (!f) { printf("ERROR no file\n"); return 1; }
    for (int i = 0; i < 4; i++) {
        file_player_v3_1_1 p(i);
        if (fread(&p, sizeof(p), 1, f) != 1) break;
        int flags = 0;
        if (p.have_shield) flags |= 1;
        if (p.can_slide) flags |= 2;
        if (p.can_charge_shot) flags |= 4;
        if (p.can_double_jump) flags |= 8;
        if (p.can_air_dash) flags |= 16;
        if (p.can_shot_diagonal) flags |= 32;
        printf("%s|%s|%d|%d|%d|%d|%d|%d|", p.name, p.graphic_filename,
            flags, p.max_shots, p.simultaneous_shots, p.damage_modifier,
            p.full_charged_projectile_id, p.normal_shot_projectile_id);
        for (int w = 0; w < 12; w++) {
            printf("%d,%d,%d;%d,%d,%d;%d,%d,%d%s",
                p.weapon_colors[w].color1.r, p.weapon_colors[w].color1.g, p.weapon_colors[w].color1.b,
                p.weapon_colors[w].color2.r, p.weapon_colors[w].color2.g, p.weapon_colors[w].color2.b,
                p.weapon_colors[w].color3.r, p.weapon_colors[w].color3.g, p.weapon_colors[w].color3.b,
                (w == 11) ? "\n" : "|");
        }
    }
    return 0;
}
'''


def parse_colour(t):
    v = tuple(int(x) for x in t.split(","))
    return None if min(v) < 0 else v


def parse_players():
    os.makedirs(WORK, exist_ok=True)
    src = os.path.join(WORK, "pl_dump.cpp")
    exe = os.path.join(WORK, "pl_dump")
    with open(src, "w") as f:
        f.write(DUMPER)
    r = subprocess.run(["g++", "-I" + ROCKBOT, "-o", exe, src],
                       cwd=ROCKBOT, capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stderr, file=sys.stderr)
        raise SystemExit("g++ failed")
    out = subprocess.run([exe], cwd=ROCKBOT, capture_output=True,
                         text=True).stdout
    players = []
    for line in out.splitlines():
        parts = line.split("|")
        if len(parts) != 8 + WEAPON_N:
            continue
        (flags, max_shots, simult, dmg, full_id,
         normal_id) = (int(x) for x in parts[2:8])
        wcol = []
        for w in range(WEAPON_N):
            c = parts[8 + w].split(";")
            wcol.append([parse_colour(c[0]), parse_colour(c[1]),
                         parse_colour(c[2])])
        players.append({
            "name": parts[0], "gfx": parts[1], "flags": flags,
            "max_shots": max_shots, "simultaneous": simult, "dmg_mod": dmg,
            "full_id": full_id, "normal_id": normal_id, "wcol": wcol,
            "c1": wcol[0][0], "c2": wcol[0][1], "c3": wcol[0][2],
        })
    return players


def main():
    players = parse_players()
    if not players:
        raise SystemExit("no players parsed")
    for p in players:
        print(f"{p['name']:10s} {p['gfx']:8s} c1={p['c1']} c2={p['c2']} "
              f"c3={p['c3']} flags={p['flags']:02X} max={p['max_shots']} "
              f"simult={p['simultaneous']} dmg={p['dmg_mod']} "
              f"full={p['full_id']} normal={p['normal_id']}")

    hdr = f"""#ifndef PLAYER_DATA_H
#define PLAYER_DATA_H

#include <genesis.h>

// Generated by tools/convert_players.py from player_list_v3_1_1.dat.
#define PLAYER_COUNT {len(players)}
#define PLAYER_WEAPON_N {WEAPON_N}

#define PL_SHIELD  {FL_SHIELD}
#define PL_SLIDE   {FL_SLIDE}
#define PL_CHARGE  {FL_CHARGE}
#define PL_DJUMP   {FL_DJUMP}
#define PL_AIRDASH {FL_AIRDASH}
#define PL_DIAG    {FL_DIAG}

typedef struct {{
    const char *name;
    s16 wcol[PLAYER_WEAPON_N][3][3]; // per weapon: {{c1, c2, c3}}; -1 = unset
    u8 max_shots, simultaneous;
    s8 dmg_mod;
    u8 flags;                 // PL_* bits
    s8 full_id;               // full-charged projectile (-1 = default 10)
    s8 normal_id;             // normal projectile (-1 = default 0)
}} PlayerData;

extern const PlayerData player_data[PLAYER_COUNT];

#endif
"""
    c = ['#include "player_data.h"\n\n',
         f"const PlayerData player_data[{len(players)}] = {{\n"]
    for p in players:
        c.append(f'    {{ "{p["name"]}",\n      {{ ')
        rows = []
        for w in range(WEAPON_N):
            cs = [p["wcol"][w][k] or (-1, -1, -1) for k in range(3)]
            rows.append("{{%d,%d,%d},{%d,%d,%d},{%d,%d,%d}}" % (
                cs[0][0], cs[0][1], cs[0][2],
                cs[1][0], cs[1][1], cs[1][2],
                cs[2][0], cs[2][1], cs[2][2]))
        c.append(",\n        ".join(rows))
        c.append(f" }},\n      {p['max_shots']}, {p['simultaneous']}, "
                 f"{p['dmg_mod']}, {p['flags']}, {p['full_id']}, "
                 f"{p['normal_id']} }},\n")
    c.append("};\n")

    with open(os.path.join(SRC, "player_data.h"), "w") as f:
        f.write(hdr)
    with open(os.path.join(SRC, "player_data.c"), "w") as f:
        f.writelines(c)
    print(f"wrote src/player_data.c/h ({len(players)} players)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
