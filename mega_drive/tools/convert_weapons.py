#!/usr/bin/env python3
"""Read the PC weapon table (game_weapons_v301.dat) into src/weapon_data.{c,h}.

`file_weapon` (file/v4/file_game_v4.h:819) is 33 bytes, no padding:
    u8   id_projectile          0
    char name[30]               1
    u8   damage                31
    u8   id_projectile_charged 32

The table index IS the weapon id (PC WEAPON_ICONS_ENUM): 0 = the default buster,
1..8 = the eight boss weapons, 9..13 = the item weapons (coil/jet/tanks),
14.. unused.

Ownership is NOT stored here: PC dataUtil::has_weapon() (data/datautil.cpp:23)
says a weapon is owned when the matching STAGE has been beaten
(`game_save.stages[weapon_n] == 1`) — the port tracks that in its save mask.

Usage: python3 tools/convert_weapons.py
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ROCKBOT = os.path.dirname(ROOT)
DATA = os.path.join(ROCKBOT, "build/games/RockDroid1")
SRC = os.path.join(ROOT, "src")

REC = 33


def parse_weapons():
    blob = open(os.path.join(DATA, "game_weapons_v301.dat"), "rb").read()
    out = []
    for i in range(len(blob) // REC):
        b = blob[i * REC:(i + 1) * REC]
        out.append({
            "id": i,
            "proj": b[0],
            "name": b[1:31].split(b"\0")[0].decode("latin1"),
            "dmg": b[31],
            "charged": b[32],
        })
    return out


def cstr(s):
    return s.replace("\\", "").replace('"', "")


def main():
    weapons = parse_weapons()
    # The switchable weapons: the buster (0) plus the eight boss weapons (1..8).
    # 9..13 are the item weapons (coil/jet/tanks) and 14.. are unused padding.
    player_n = max(w["id"] for w in weapons if w["id"] <= 8 and w["name"]) + 1
    for w in weapons:
        print(f'{w["id"]:2d} proj={w["proj"]:3d} dmg={w["dmg"]:3d} '
              f'charged={w["charged"]:3d}  {w["name"]!r}')

    hdr = f"""#ifndef WEAPON_DATA_H
#define WEAPON_DATA_H

#include <genesis.h>

// Generated by tools/convert_weapons.py from game_weapons_v301.dat.
#define WEAPON_N {len(weapons)}
// Switchable player weapons: 0 (buster) .. {player_n - 1} (the eight bosses).
#define WEAPON_PLAYER_N {player_n}

typedef struct {{
    const char *name;
    u8 proj;    // id_projectile (index into stage_def->enemy_proj)
    u8 dmg;
}} WeaponData;

extern const WeaponData weapon_data[WEAPON_N];

#endif
"""
    c = ['#include "weapon_data.h"\n\n',
         f"const WeaponData weapon_data[{len(weapons)}] = {{\n"]
    for w in weapons:
        c.append(f'    {{ "{cstr(w["name"])}", {w["proj"]}, {w["dmg"]} }},\n')
    c.append("};\n")

    with open(os.path.join(SRC, "weapon_data.h"), "w") as f:
        f.write(hdr)
    with open(os.path.join(SRC, "weapon_data.c"), "w") as f:
        f.writelines(c)
    print(f"wrote src/weapon_data.c/h ({len(weapons)} weapons)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
