#!/usr/bin/env python3
"""Convert the PC sound effects for the XGM2 driver.

Reads build/games/RockDroid1/sfx/<name>.wav (8 bit, 11 kHz, some stereo) and
writes, for each SFX the port actually uses:

  res/sfx/<name>.wav   2x gain, mixed to mono, 16 bit (rescomp's `XGM2` WAV
                       plugin converts it to the 8 bit / 13.3 kHz PCM the
                       driver plays)
  res/sfx_pcm.res      one `WAV sfx_<name> "sfx/<name>.wav" XGM2` line per
                       sound (rescomp generates res/sfx_pcm.h); the runtime
                       plays them with
                       XGM2_playPCM(sfx_<name>, sizeof(sfx_<name>), ch)

The 2x gain is borrowed from tools_zanake/gen_sfx.py: the PC effects peak
well under half scale and would be inaudible next to the FM music; the same
gain for all keeps their relative balance (the few loud ones clip).
"""
import array
import os
import sys
import wave

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ROCKBOT = os.path.dirname(ROOT)
DATA = os.path.join(ROCKBOT, "build/games/RockDroid1/sfx")
RES = os.path.join(ROOT, "res")
GAIN = 2

# SFX the port uses today (PC names). Checkpoint/stage-clear jingles and the
# charge loop come later (music-side milestone).
SOUNDS = [
    # player
    "player_shot", "charged_shot", "player_jump", "player_hit", "player_death",
    # charge loop (PC loops charging1 while charging, charging2 once full —
    # the port re-triggers them every ~0.45s instead)
    "charging1", "charging2",
    # enemies / boss
    "npc_hit", "npc_killed", "big_explosion",
    # objects
    "got_energy_pill", "got_item", "teleporter_activated",
    # UI
    "cursor",
]


def load_mono(path):
    with wave.open(path, "rb") as w:
        p = w.getparams()
        data = w.readframes(p.nframes)
        ch = p.nchannels
        width = p.sampwidth
    if width == 1:
        samples = [(b - 128) << 8 for b in data]
    elif width == 2:
        samples = array.array("h", data)
        if sys.byteorder == "big":
            samples.byteswap()
    else:
        sys.exit("%s: %d bit not supported" % (path, width * 8))
    if ch == 2:                      # XGM2's DAC is mono
        samples = array.array("h", ((samples[i] + samples[i + 1]) // 2
                                    for i in range(0, len(samples), 2)))
    elif ch != 1:
        sys.exit("%s: %d channels not supported" % (path, ch))
    return samples, p.framerate


def main():
    sfx_dir = os.path.join(RES, "sfx")
    os.makedirs(sfx_dir, exist_ok=True)
    lines = ["// Generated by tools/convert_sfx.py. Do not edit.", ""]
    total = 0
    for name in SOUNDS:
        src = os.path.join(DATA, name + ".wav")
        if not os.path.isfile(src):
            print(f"  SKIP {name}: {src} not found")
            continue
        samples, rate = load_mono(src)
        louder = array.array("h", (max(-32768, min(32767, s * GAIN))
                                   for s in samples))
        if sys.byteorder == "big":
            louder.byteswap()
        dst = os.path.join(sfx_dir, name + ".wav")
        with wave.open(dst, "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(rate)
            w.writeframes(louder.tobytes())
        # XGM2 plays 8 bit at ~13.3 kHz: that is the size it will occupy
        kb = len(samples) * 13300 / rate / 1024
        total += kb
        print(f"  {name:22s} {len(samples)/rate:5.2f}s @{rate}Hz -> ~{kb:5.1f}KB at 13.3kHz")
        lines.append(f'WAV sfx_{name} "sfx/{name}.wav" XGM2')
    # name != sfx.res: rescomp names the generated header after the .res
    # (sfx.res -> sfx.h would collide with src/sfx.h)
    with open(os.path.join(RES, "sfx_pcm.res"), "w", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")
    print(f"{len(lines) - 2} sounds, ~{total:.0f}KB of PCM in ROM")
    return 0


if __name__ == "__main__":
    sys.exit(main())
