#!/usr/bin/env python3
"""Ending enemy parade data (PC scenesLib::show_enemies_ending).

The PC shows every enemy of game_enemy_list that is NOT a stage boss, 3 s each:
the boss-intro background, the enemy's first frame (its first INTRO frame when it
has one) and its name. The ROM only carries the sprites of the enemies placed in
converted stages and no names, so this writes the whole list:

  res/parade_<id>.png   first frame, copied 1:1 from the hand-owned indexed art
  res/parade.res        one SPRITE line per frame
  src/parade_data.c/h   names + sprite + frame size, in list order

Enemies without art in images/sprites/enemies are skipped (printed).
"""
import os
import struct
import sys

from PIL import Image

sys.argv = sys.argv[:1]           # convert_enemies reads argv[1] as the stage index
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import convert_enemies as C       # noqa: E402

ROOT = C.ROOT
DATA = C.DATA
RES = C.RES
SRC = C.SRC
ART = os.path.join(C.IMAGES, "sprites", "enemies")
MAX_W, MAX_H = 128, 80            # one sprite on screen at a time
ANIM_INTRO = C.ANIM_INTRO


def stage_boss_ids():
    blob = open(os.path.join(DATA, "stages_v301.dat"), "rb").read()
    ids = set()
    for s in range(len(blob) // C.STAGE_SZ):
        b = struct.unpack_from("<b", blob, C.STAGE_SZ * s + C.STAGE_BOSS_OFF)[0]
        if b >= 0:
            ids.add(b)
    return ids


def main():
    blob = open(os.path.join(DATA, "game_enemy_list_3_1_2.dat"), "rb").read()
    n = len(blob) // C.NPC_SZ
    bosses = stage_boss_ids()
    rows, res = [], []
    for eid in range(n):
        if eid in bosses:
            continue
        b = blob[eid * C.NPC_SZ:(eid + 1) * C.NPC_SZ]
        name, gfx = C.cstr(b, 3, 30), C.cstr(b, 33, 30)
        fw = struct.unpack_from("<b", b, 5958)[0]
        fh = struct.unpack_from("<b", b, 5959)[0]
        path = os.path.join(ART, gfx)
        if not gfx or fw <= 0 or fh <= 0 or not os.path.exists(path):
            print(f"  skip {eid} '{name}': no art ({gfx!r}, {fw}x{fh})")
            continue
        if fw > MAX_W or fh > MAX_H:
            print(f"  skip {eid} '{name}': frame {fw}x{fh} too big")
            continue
        # PC draw::show_boss_intro_sprites: with more than one INTRO frame they play
        # in order with their own durations (the last one stays); otherwise the
        # first frame of the sheet is shown (NOT the stand/intro frame by position).
        intro = []
        for f in range(10):
            o = 78 + (ANIM_INTRO * 10 + f) * 14
            if b[o]:
                intro.append((b[o + 4], struct.unpack_from("<H", b, o + 2)[0]))
        im, pal = C.load_indexed(path)
        if len(intro) > 1:
            cols = [c for c, _ in intro]
            ticks = [max(1, round(d * 60 / 1000)) for _, d in intro]
        else:
            cols, ticks = [0], [0]
        cols = [c if (c + 1) * fw <= im.width else 0 for c in cols]
        cw, ch = C.ceil8(fw), C.ceil8(fh)
        out = Image.new("P", (cw * len(cols), ch), 0)
        out.putpalette(im.getpalette())
        for i, c in enumerate(cols):
            out.paste(im.crop((c * fw, 0, c * fw + fw, fh)), (i * cw, 0))
        fn = f"parade_{eid}.png"
        out.save(os.path.join(RES, fn), transparency=0)
        res.append(f'SPRITE parade_{eid}_sprite "{fn}" {cw}p {ch}p FAST [[{",".join(map(str, ticks))}]]')
        rows.append((eid, name, fw, fh))
    open(os.path.join(RES, "parade.res"), "w").write("\n".join(res) + "\n")
    with open(os.path.join(SRC, "parade_data.h"), "w") as f:
        f.write("#ifndef PARADE_DATA_H\n#define PARADE_DATA_H\n\n#include <genesis.h>\n\n"
                "// Generated by tools/convert_parade.py: PC enemy list minus the stage bosses.\n"
                f"#define PARADE_COUNT {len(rows)}\n"
                "typedef struct { const char *name; const SpriteDefinition *spr; u8 w, h; } ParadeEnemy;\n"
                "extern const ParadeEnemy parade_enemies[PARADE_COUNT];\n\n#endif\n")
    with open(os.path.join(SRC, "parade_data.c"), "w") as f:
        f.write('#include "parade_data.h"\n#include "parade.h"      // generated by rescomp from res/parade.res\n\n'
                "const ParadeEnemy parade_enemies[PARADE_COUNT] = {\n")
        for eid, name, w, h in rows:
            f.write('    { "%s", &parade_%d_sprite, %d, %d },\n' % (name.upper().replace('"', ''), eid, w, h))
        f.write("};\n")
    print(f"wrote {len(rows)} parade enemies")


if __name__ == "__main__":
    main()
