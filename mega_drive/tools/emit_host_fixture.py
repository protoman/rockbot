#!/usr/bin/env python3
"""Emit a host cost-test fixture that mirrors one real stage room.

The perf reports are always "slowdown in <room> with lots of objects", so the
host test has to run the SAME object mix and the SAME terrain as the room, not a
synthetic pill grid. This reads the generated converters' output and writes a
plain C fixture (no SGDK types) that tests/host/objects_cost.c can load:

    tests/host/fixtures/stage<N>_map<M>.c/.h

It carries, per object: the PC type, frame count/delay, size, speed, timer,
limit and the two animation flags - plus every spawn of that map and the map's
terrain grid (so gravity/platform probes see the real floor).

Usage: tools/emit_host_fixture.py 0 1
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
OUT = os.path.join(ROOT, "tests/host/fixtures")


def read(path):
    with open(path, errors="replace") as f:
        return f.read()


def parse_defs(stage):
    text = read(os.path.join(SRC, f"stage{stage}_objects.c"))
    defs = []
    for m in re.finditer(
            r"/\* (\d+) \*/ \{ &(\w+)_sprite, (\d+), (\d+), (\d+), "
            r"(\d+), (\d+), (-?\d+), (\d+), (\d+), (\d+), (\d+) \}", text):
        (i, spr, typ, frames, frame_t, w, h, speed, timer, limit,
         auto, loop) = m.groups()
        defs.append(dict(index=int(i), name=spr, type=int(typ),
                         frames=int(frames), frame_t=int(frame_t),
                         w=int(w), h=int(h), speed=int(speed),
                         timer=int(timer), limit=int(limit),
                         anim_auto=int(auto), anim_loop=int(loop)))
    if not defs:
        sys.exit(f"stage{stage}_objects.c: no object defs parsed")
    return defs


def parse_spawns(stage):
    text = read(os.path.join(SRC, f"stage{stage}_objects.c"))
    block = re.search(r"stage\d+_object_spawns\[[^\]]*\] = \{(.*?)\n\};",
                      text, re.S)
    if not block:
        sys.exit("spawn table not found")
    spawns = []
    for m in re.finditer(r"\{\s*(\d+),\s*(\d+),\s*(-?\d+),\s*(-?\d+),",
                         block.group(1)):
        d, mp, x, y = (int(g) for g in m.groups())
        spawns.append((d, mp, x, y))
    return spawns


def parse_terrain(stage, map_n):
    text = read(os.path.join(SRC, f"stage{stage}_data.c"))
    m = re.search(r"static const u8 stage\d+_terrain\[(\d+)\]\[(\d+)\] = \{(.*?)\n\};",
                  text, re.S)
    if not m:
        sys.exit("terrain array not found")
    maps, size = int(m.group(1)), int(m.group(2))
    rows = re.findall(r"\{([^{}]*)\}", m.group(3))
    if len(rows) < maps:
        # the array may be written as one brace per map row
        rows = [r for r in re.findall(r"\{([^{}]*)\}", m.group(3))]
    row = rows[map_n]
    values = [int(v) for v in re.findall(r"\d+", row)]
    if len(values) < size:
        sys.exit(f"terrain map {map_n}: {len(values)} values, expected {size}")
    return values[:size]


def main(argv):
    if len(argv) != 3:
        sys.exit("usage: tools/emit_host_fixture.py <stage> <map>")
    stage, map_n = int(argv[1]), int(argv[2])
    defs = parse_defs(stage)
    spawns = [s for s in parse_spawns(stage) if s[1] == map_n]
    terrain = parse_terrain(stage, map_n)
    map_h = 14
    map_w = len(terrain) // map_h

    os.makedirs(OUT, exist_ok=True)
    base = f"stage{stage}_map{map_n}"
    with open(os.path.join(OUT, base + ".h"), "w") as f:
        f.write("// Generated by tools/emit_host_fixture.py - do not edit.\n")
        f.write(f"#ifndef HOST_FIXTURE_{base.upper()}_H\n")
        f.write(f"#define HOST_FIXTURE_{base.upper()}_H\n\n")
        f.write(f"#define FX_MAP_W {map_w}\n#define FX_MAP_H {map_h}\n")
        f.write(f"#define FX_DEF_COUNT {len(defs)}\n")
        f.write(f"#define FX_SPAWN_COUNT {len(spawns)}\n")
        f.write("typedef struct { unsigned char type, frames; unsigned short"
                " frame_t; unsigned char w, h; signed char speed;"
                " unsigned short timer, limit; unsigned char anim_auto,"
                " anim_loop; const char *name; } FxDef;\n")
        f.write("typedef struct { unsigned char def, map; short x, y; } FxSpawn;\n")
        f.write("extern const FxDef fx_defs[];\n")
        f.write("extern const FxSpawn fx_spawns[];\n")
        f.write("extern const unsigned char fx_terrain[];\n\n#endif\n")
    with open(os.path.join(OUT, base + ".c"), "w") as f:
        f.write("// Generated by tools/emit_host_fixture.py - do not edit.\n")
        f.write(f'#include "{base}.h"\n\n')
        f.write("const FxDef fx_defs[] = {\n")
        for d in defs:
            f.write(f'    {{ {d["type"]}, {d["frames"]}, {d["frame_t"]}, '
                    f'{d["w"]}, {d["h"]}, {d["speed"]}, {d["timer"]}, '
                    f'{d["limit"]}, {d["anim_auto"]}, {d["anim_loop"]}, '
                    f'"{d["name"]}" }},\n')
        f.write("};\n\nconst FxSpawn fx_spawns[] = {\n")
        for (d, mp, x, y) in spawns:
            f.write(f"    {{ {d}, {mp}, {x}, {y} }},\n")
        f.write("};\n\nconst unsigned char fx_terrain[] = {\n")
        for i in range(0, len(terrain), map_w):
            f.write("    " + ",".join(str(v) for v in terrain[i:i + map_w]) + ",\n")
        f.write("};\n")
    print(f"wrote tests/host/fixtures/{base}.c/.h: {len(defs)} defs, "
          f"{len(spawns)} spawns on map {map_n}, terrain {map_w}x{map_h}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
