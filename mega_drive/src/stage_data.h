// Shared stage types + the StageDef the runtime reads. The per-stage arrays
// are generated by tools/convert_stage.py / convert_enemies.py /
// convert_objects.py; each stage exposes ONE `stageN_def` symbol.

typedef struct {
    u8 map_from, tile_x, tile_y, map_to, dst_x, dst_y;
    u8 size;        // PC file_link.size: activation band width in tiles
    u8 bidir;       // PC file_link.bidirecional: reverse direction allowed
    u8 type;        // PC LINK_TYPES: 0/1 vertical scroll, >=2 teleporter
} StageLink;

typedef struct { u8 present; s16 adjust_y; s8 speed; u8 auto_scroll; } StageBgInfo;

typedef struct { u8 x, y, slot, tile3; } StageAnimCell;
typedef struct { u8 frames; u16 delay[6]; } StageAnimSlot;   // delay in frames

typedef struct {
    const SpriteDefinition *spr;
    u8 npc_id;          // PC npc id (AI SPAWN_NPC target lookup)
    u8 hp;              // shots to kill (file_npc.hp.total; boss = 36)
    u8 dmg_mul;         // weakness[0].damage_multiplier
    u8 speed;           // px/frame
    u8 fly;             // 1 = no gravity
    u8 is_boss;
    u8 is_sub_boss;     // PC file_npc.is_sub_boss (doors wait for it)
    u16 respawn_delay;  // PC respawn_delay in ms (0 = none)
    u8 shot;            // default projectile id
    u16 range;          // AI walk/wait distance
    s16 box_l, box_t;
    u16 box_w, box_h;
    u8 stand_n, walk_n, attack_n;
    u8 jump_anim, teleport_anim;  // sheet row of JUMP/TELEPORT, 255 = none
    u8 intro_anim;                // sheet row of ANIM_TYPE_INTRO (bosses), 255 = none
    u16 intro_ms;                 // its total duration in ms
    u16 attack_ms;
    u8 shield_type;     // e_shield_types: SHIELD_STAND etc. (character.cpp:3357)
    u8 weak[9];         // PC weakness[weapon].damage_multiplier (0 = immune)
    u8 turn_anim;       // sheet row of ANIM_TYPE_TURN (255 = none): the enemy
                        // turns by playing it (the flying shielder rotates)
    u16 turn_ms;        // its total duration in ms
    u16 attack_shot_ms; // ms from the start of the attack animation to the frame
                        // that spawns the projectile (PC file_npc.attack_frame,
                        // else the last frame; character.cpp:936 / ai.cpp:1185)
    u8 air_anim;        // sheet row of ANIM_TYPE_WALK_AIR (255 = none): the clinging pose after GRAB_WALL
    u8 slide_anim;      // sheet row of ANIM_TYPE_SLIDE (255 = none): the DASH pose
    u8 jatk_anim;       // sheet row of ANIM_TYPE_JUMP_ATTACK (255 = none)
    u8 frame_h;         // PC frame height: touch damage is BIG unless the NPC is taller than the player (29)
    u8 frame_w;
    u8 vul_x, vul_y, vul_w, vul_h;  // PC vulnerable_area: what player shots can hit (0 size = the collision box)
} EnemyDef;

typedef struct {
    u8 chance, action, go_to;
    u16 delay;
    s8 param;
} EnemyAi;

typedef struct {
    const SpriteDefinition *spr;
    u8 speed, dmg, w, h;
    u8 traj;            // PROJECTILE_TRAJECTORIES (defines.h)
    u8 max_shots;       // 0 = unlimited
} EnemyProj;

typedef struct {
    u8 def, map;
    s16 x, y, x_min, x_max;
    u8 dir;
} EnemySpawn;

typedef struct {
    const SpriteDefinition *spr;
    u8 type;            // PC OBJECT_TYPE value
    u8 frames;
    u16 frame_t;        // ticks (1/60s) per frame
    u8 w, h;
    s8 speed;
    u16 timer;          // PC file_object.timer: beam delay / block initial delay
    u16 limit;          // PC file_object.limit: LR platform travel range
    // PC file_object animation flags: auto = animate without being started,
    // loop = the animation repeats (the checkpoint's flag loops once active).
    u8 anim_auto, anim_loop;
} ObjectDef;

typedef struct {
    u8 def, map;
    s16 x, y;
    u8 dest_x, dest_y, dest_map;   // teleporter (type 32) only
} ObjectSpawn;

// ---- per-stage bundle --------------------------------------------------
typedef struct {
    u8 map_count, map_w, map_h, tile;

    const MapDefinition *const *map_defs;
    const TileSet *const *tile_sets;
    const Palette *const *palettes;
    const u8 *terrain;                  // [map_count][map_w*map_h]

    const StageLink *links;
    u8 link_count;

    const StageBgInfo *bg_info;         // [map_count]
    // PC map_data.background_color as RGB333 ([map_count][3]): the colour
    // the PC clears the screen with before the background image, so it
    // shows wherever the image does not reach (MD backdrop, CRAM 0).
    const u8 *bg_color;
    const Palette *const *bg_pal;       // [map_count], NULL = no bg
    const u32 *const *bg_tiles;
    const u16 *bg_tiles_n;
    const u16 *const *bg_maps;
    const u16 *bg_map_h;

    const u8 *scroll_lock_n;            // [map_count]
    const u8 *scroll_lock;              // [map_count][scroll_lock_max]
    u8 scroll_lock_max;

    const u8 *tile3_mask;               // [map_count][mask_bytes]
    // Colourcycle: cells drawn with PAL3-relative art (their palette line is
    // switched at plane-write time) plus the PAL3 band the runtime rotates.
    // cycle_n == 0 when the stage has no pool (see stage0_plan.md).
    const u8 *pal3_mask;                // [map_count][mask_bytes]
    u16 cycle_base;                     // first PAL3 entry of the band
    u8 cycle_n;                         // band length (0 = no colourcycle)
    u8 cycle_frames;                    // frames per rotation step
    const u16 *cycle_colors;            // [cycle_n] CRAM words, rotation order
    const u8 *anim_cell_slot;           // [map_count][map_w*map_h], 0=none else slot+1
    const u8 *anim_slot_n;              // [map_count]
    u8 anim_slot_max;
    const StageAnimSlot *anim_slots;    // [map_count][anim_slot_max]
    const u16 (*anim_frames)[6][64];    // [map_count][anim_slot_max][6][64]

    const EnemyDef *enemy_defs;
    u8 enemy_def_count;
    const EnemySpawn *enemy_spawns;
    u16 enemy_spawn_count;
    const EnemyAi (*enemy_ai)[20];
    // PC artificial_inteligence.reactions[6]: PLAYER_ON_RANGE, HIT, DEAD,
    // PLAYER_SAME_Y, PLAYER_CLOSE, PLAYER_SAME_X (action 0 = inactive,
    // go_to 0 = back to the chance roll).
    const EnemyAi (*enemy_react)[6];
    const EnemyProj *enemy_proj;
    u8 enemy_proj_max;

    const ObjectDef *object_defs;
    u8 object_def_count;
    const ObjectSpawn *object_spawns;
    u16 object_spawn_count;
} StageDef;

// Defined stages, in order. The stage select maps its slots to these.
